#!/usr/bin/env python3
"""Generate random audit records for the per-field comparison.

t/gen.py writes the corpus, and everything in it is a shape somebody
thought of.  This writes records nobody thought of: field names and
values drawn at random from the alphabet the format allows, in all
three encodings, at lengths and byte values a hand-written case would
not reach.  What reads them is the same pair of programs as always,
auditp and ausearch, compared field by field, so the oracle is no
weaker here than anywhere else.

Seeded, and the seed is the only input.  --digest prints a hash of the
generated bytes rather than of any report about them: a determinism
check that compares two reports passes while the seed is being ignored,
because the report echoes the seed back at the top.

Three constructs are deliberately NOT generated, each because ausearch's
output cannot express them rather than because auditp cannot read them:

  A decoded value containing " name=", which is indistinguishable in
  ausearch's output from the end of one field and the start of another.

  A value that is a single space, or ends in one.  ausearch writes a
  space after every field, so the last one cannot be recovered.

  A field name that repeats inside one record more than twice, which
  the comparison can line up but not name.

Those three are the format's limits on the comparison and are in the
README.  Everything else is fair.
"""

import argparse
import hashlib
import random
import sys

# EXECVE is not here.  Its a0..aN are argv elements rather than syscall
# arguments, and libaudit reads that record positionally, so a random
# field list inside one makes it decode the arch as a byte string.  The
# corpus covers EXECVE properly; this generator cannot.
TYPES = ["SYSCALL", "PATH", "CWD", "PROCTITLE", "USER_CMD",
         "SOCKADDR", "AVC", "BPF", "SECCOMP", "ANOM_ABEND", "TTY",
         "CONFIG_CHANGE", "MQ_OPEN", "FEATURE_CHANGE", "KERN_MODULE",
         "SERVICE_START", "USER_AUTH", "CRED_ACQ", "OBJ_PID", "IPC",
         "UNKNOWN[1100]", "UNKNOWN[9999]"]

# The types that share an event with another record.  ausearch puts a
# user-space record in an event of its own even when another record has
# the same timestamp and serial, and auditp groups by the key alone, so
# the two disagree about how many records the event has and every index
# after the first shifts.  That is a real difference in event assembly
# and it is in the README and the plan; until auditp implements the
# rule, a multi-record event here is built from the kernel types only.
GROUPABLE = ["SYSCALL", "PATH", "CWD", "PROCTITLE", "SOCKADDR", "AVC",
             "BPF", "SECCOMP", "TTY", "MQ_OPEN", "IPC"]

# Field names, grouped by the shape of value the kernel writes for them.
# The fuzzer does NOT put a value of the wrong shape in a field: a uid
# that is not a number, or a signal that is sixteen hex digits, measures
# libaudit's strtoul rather than either parser.  ausearch renders
# uid=(none) as root, because strtoul of "(none)" is 0, and auditp
# leaves it alone; that disagreement is real and is in the README, and
# generating thousands of them would bury everything else.
ESCAPED = ["comm", "exe", "name", "cwd", "cmd", "path", "acct", "ocomm",
           "proctitle", "key", "sw", "root_dir", "data"]
IDS = ["uid", "gid", "auid", "euid", "suid", "fsuid", "egid", "sgid",
       "fsgid", "ouid", "ogid"]
DECIMAL = ["pid", "ppid", "items", "item", "inode", "prog-id", "ses",
           "sig", "list", "family", "syscall", "exit"]
HEX = ["a0", "a1", "a2", "a3", "arch", "oflag", "flags", "code",
       "cap_fp", "cap_fi", "cap_fe", "cap_fver", "cap_frootid"]
WORDS = ["nametype", "success", "res", "op", "tty", "subj", "obj", "dev",
         "rdev", "mode"]
PLAIN = IDS + DECIMAL + HEX + WORDS + ["saddr"]

SAFE_TEXT = ("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"
             "0123456789/._-+:,@[]{}()<>!#$%^&*;?~|")


def rand_bytes(r, n):
    """Bytes for a hex-encoded value: anything at all except what makes
    ausearch's output ambiguous."""
    out = bytearray()
    while len(out) < n:
        c = r.randrange(0, 256)
        if c in (0x3D, 0x22, 0x27, 0x01):
            # '=' can invent a field boundary in ausearch's output;
            # a quote at the start of a decoded value makes its own
            # splitter read to the next quote and swallow the fields
            # after it; and 0x01 is the separator the kernel puts
            # between two audit keys, so ausearch cuts a key= value
            # there and prints the first part only.  All three are
            # limits of the output format rather than of either
            # parser.
            continue
        if c == 0x20 and (len(out) == 0 or out[-1] == 0x20):
            continue                        # leading or doubled space
        out.append(c)
    while out and out[-1] == 0x20:
        out.pop()
    return bytes(out) if out else b"x"


def rand_text(r, n):
    return "".join(r.choice(SAFE_TEXT) for _ in range(n))


WORD_VALUES = {
    "nametype": ["NORMAL", "PARENT", "CREATE", "DELETE", "UNKNOWN"],
    "success": ["yes", "no"],
    "res": ["success", "failed", "0", "1"],
    "op": ["LOAD", "UNLOAD", "add_rule", "remove_rule", "PAM:accounting"],
    "tty": ["pts0", "pts4", "tty3", "(none)", "?"],
    "subj": ["system_u:system_r:widget_t:s0", "unconfined_u:unconfined_r:"
             "frob_t:s0-s0:c0.c511", "?"],
    "obj": ["system_u:object_r:widget_data_t:s0", "?"],
    "dev": ["fd:01", "00:05", "08:02"],
    "rdev": ["00:00", "01:03"],
    "mode": ["0100644", "040755", "0120777", "0140777", "010644", "060660",
             "020666", "0104755", "0100000", "0101644"],
}


def value(r, name):
    """One field value, in whichever encodings that field can take."""
    if name == "proctitle":
        # An argv, not random bytes.  A proctitle is the one field
        # where a NUL separates arguments rather than ending the
        # string, and ausearch's handler for it splits the HEX TEXT on
        # the characters 00 rather than splitting the decoded bytes,
        # so a NUL that lands on an odd nibble boundary cuts a byte in
        # half and the rest of the value comes out as raw hex.  Random
        # bytes hit that about once in a hundred records and there is
        # nothing to compare against when they do.
        argv = b"\0".join(rand_text(r, r.randrange(1, 12)).encode()
                          for _ in range(r.randrange(1, 5)))
        if r.randrange(0, 4):
            return argv.hex().upper()
        return '"' + argv.split(b"\0")[0].decode() + '"'
    if name in ESCAPED:
        pick = r.randrange(0, 100)
        if pick < 45:
            return rand_bytes(r, r.randrange(1, 40)).hex().upper()
        if pick < 90:
            return '"' + rand_text(r, r.randrange(1, 30)) + '"'
        return "(null)"
    if name in WORD_VALUES:
        return r.choice(WORD_VALUES[name])
    if name in IDS:
        return r.choice(["0", "1", "2", "8", "12", "1000", "65534",
                         "60123", "4294967295",
                         "%d" % r.randrange(0, 70000)])
    if name == "saddr":
        n = r.choice([2, 4, 12, 16, 28, 110])
        return rand_bytes(r, n).hex().upper()[:2 * n]
    if name == "exit":
        return "%d" % (r.randrange(0, 4096) * r.choice([1, 1, -1]))
    if name == "arch":
        return r.choice(["c000003e", "40000003"])
    if name in ("oflag", "flags", "code"):
        # With the 0x the kernel writes.  Without it ausearch reads the
        # digits as DECIMAL, because it uses strtoul with base 0, and
        # auditp reads them as hex; the kernel never writes them that
        # way and the README records the difference rather than the
        # fuzzer generating thousands of it.
        return "0x%x" % r.randrange(0, 1 << r.choice([4, 8, 16, 32]))
    if name == "syscall":
        return "%d" % r.randrange(0, 460)
    if name == "sig":
        return "%d" % r.randrange(0, 40)
    if name in DECIMAL:
        return "%d" % r.randrange(0, 1 << r.choice([4, 8, 16, 32]))
    return "%x" % r.randrange(0, 1 << r.choice([4, 8, 16, 32, 63]))


# Values for the fields inside a nested msg='...'.  ausearch interprets
# several of them and rewrites what it does not recognise: addr=:%,m
# comes back as :% m, and res= of anything but a known word comes back
# with a word appended.  Random text in those two measures libaudit's
# rewriting rather than either parser, so they get values of the shape
# they carry in a real record.
NESTED_VALUES = {
    "addr": ["?", "10.0.0.1", "2001:db8::1", "0.0.0.0"],
    "res": ["success", "failed"],
    "terminal": ["pts/0", "pts/4", "tty3", "?", "(none)"],
    "hostname": ["?", "node-a", "node-b"],
    "op": ["PAM:authentication", "PAM:accounting", "PAM:session_open"],
}


def nested(r):
    """A single-quoted msg= holding a whole second field list."""
    parts = []
    for _ in range(r.randrange(2, 7)):
        n = r.choice(["op", "grantors", "acct", "exe", "hostname", "addr",
                      "terminal", "res", "unit", "comm"])
        if n in NESTED_VALUES:
            v = r.choice(NESTED_VALUES[n])
        elif n in ("acct", "exe", "comm"):
            v = '"' + rand_text(r, r.randrange(1, 15)) + '"'
        else:
            v = rand_text(r, r.randrange(1, 12)).replace('"', "x")
        parts.append("%s=%s" % (n, v))
    # Never a quoted value last.  ausearch strips the quotes from the
    # last field of a nested list by truncating at the closing one, and
    # the closing apostrophe of the whole list goes with it, so its own
    # output is unbalanced and there is nothing to compare against.
    parts.append("res=" + r.choice(["success", "failed"]))
    return "'" + " ".join(parts) + "'"


def record(r, serial, grouped=False):
    typ = r.choice(GROUPABLE if grouped else TYPES)
    body = []
    if typ == "AVC" and r.randrange(0, 2):
        body.append("avc:  denied  { %s } for " %
                    r.choice(["read", "write", "read write", "execute"]))
    nf = r.randrange(1, 14)
    names = []
    for _ in range(nf):
        n = r.choice(ESCAPED + PLAIN)
        # arch and syscall at most once each.  ausearch renders a
        # repeated arch as a single raw byte of the value, which is its
        # own defect and not a rendering to compare against.
        if n in ("arch", "syscall") and n in names:
            continue
        # A syscall number or a syscall argument only in a record type
        # that has them.  Elsewhere ausearch prints the name of syscall
        # 0 whatever the number says, the same defect it has when the
        # record carries no arch.
        if n in ("syscall", "a0", "a1", "a2", "a3") \
                and typ not in ("SYSCALL", "SECCOMP"):
            continue
        names.append(n)
    # data= goes last if it is there at all.  ausearch's keystroke
    # renderer is the one field renderer that does not append the
    # trailing space every other field gets, so a data= with a field
    # after it comes out as ...B\205"cmd=o?Mm, glued together with no
    # separator, and no reader can take them apart again.
    # A record carrying a syscall number or a syscall argument gets an
    # arch as well.  Without one ausearch prints "read" for every
    # syscall number there is, because it renders the number it has not
    # read yet, and comparing against that would be comparing against a
    # defect rather than against an authority.
    if any(n in ("syscall", "a0", "a1", "a2", "a3") for n in names):
        if "arch" not in names:
            names.append("arch")
        if "syscall" not in names:
            names.append("syscall")
        # arch and syscall FIRST, because ausearch interprets a record
        # field by field with a running state: an a3 that appears
        # before the syscall number is rendered against syscall 0 and
        # comes out as plain hex.  The kernel always writes arch and
        # syscall first and a reader that looked for them anywhere is
        # not wrong, but the two cannot be compared on a record that
        # does not.
        names = ["arch", "syscall"] + [n for n in names
                                       if n not in ("arch", "syscall")]
    # And only the two architectures ausearch has a syscall table for.
    # For any other it prints the name of syscall 0 whatever the number
    # is, which is the same defect as having no arch at all.
    for name in names:
        if name != "data":
            body.append("%s=%s" % (name, value(r, name)))
    # A nested msg only in a record that has another field as well.
    # With msg= alone ausearch does not interpret the inner list at
    # all and echoes it with its quotes on, while with any other field
    # present it interprets every one of them.  Measured; no record
    # the kernel writes has msg= and nothing else.
    if r.randrange(0, 10) == 0 and len(body) > 1:
        body.append("msg=" + nested(r))
    # data= goes last in the record if it is there at all, nested msg
    # included.  ausearch's keystroke renderer is the one field
    # renderer that does not append the trailing space every other
    # field gets, so a data= with anything after it comes out glued to
    # it, as ...a8sEXf:l{m*Ww"msg='grantors=o ..., and no reader can
    # take the two apart again.
    if "data" in names:
        body.append("data=%s" % value(r, "data"))
    line = "type=%s msg=audit(17000000%02d.%03d:%d): %s" % (
        typ, r.randrange(0, 100), r.randrange(0, 1000), serial,
        " ".join(body).replace("  ", "  ", 1))
    if r.randrange(0, 20) == 0:
        line = "node=%s %s" % (r.choice(["node-a", "node-b"]), line)
    return line


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--count", type=int, default=400)
    ap.add_argument("--out", required=True)
    ap.add_argument("--digest", action="store_true")
    args = ap.parse_args()

    r = random.Random(args.seed)
    lines = []
    serial = 5000
    while len(lines) < args.count:
        # Some events get several records, which is what the correlator
        # is for; the serial only advances between events.
        n = r.choice([1, 1, 1, 2, 3, 4])
        for _ in range(n):
            lines.append(record(r, serial, grouped=n > 1))
            if len(lines) >= args.count:
                break
        serial += 1
    blob = ("\n".join(lines) + "\n").encode("utf-8", "surrogateescape")
    with open(args.out, "wb") as f:
        f.write(blob)
    if args.digest:
        print("digest %s" % hashlib.sha256(blob).hexdigest())
    print("records %d" % len(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
